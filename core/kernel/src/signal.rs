/// sigaction flags.
pub(crate) mod sa {
    /// Do not send SIGCHLD when a child stops or continues.
    pub const NOCLDSTOP: u64 = 0x1;
    /// Children do not become zombies when they exit.
    pub const NOCLDWAIT: u64 = 0x2;
    /// The handler receives siginfo and ucontext.
    pub const SIGINFO: u64 = 0x4;
    /// `sa_restorer` is valid.
    pub const RESTORER: u64 = 0x0400_0000;
    /// Run the handler on the alternate stack.
    pub const ONSTACK: u64 = 0x0800_0000;
    /// Interrupted syscalls are restarted automatically.
    pub const RESTART: u64 = 0x1000_0000;
    /// Do not block this signal while its handler runs.
    pub const NODEFER: u64 = 0x4000_0000;
    /// Restore the default disposition after one delivery.
    pub const RESETHAND: u64 = 0x8000_0000;
}

/// One signal's disposition (the layout of `struct k_sigaction` on arm64).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub(crate) struct SigAction {
    pub handler: u64,
    pub flags: u64,
    pub restorer: u64,
    pub mask: u64,
    /// The default disposition forced when seccomp kills the process (Linux's `SA_IMMUTABLE`): it
    /// cannot be changed again, and tracers cannot intercept it ([`force_fatal`]).
    pub immutable: bool,
}

impl SigAction {
    /// `SIG_DFL`.
    pub const DEFAULT: u64 = 0;
    /// `SIG_IGN`.
    pub const IGNORE: u64 = 1;
}

/// A thread group's signal dispositions (`CLONE_SIGHAND` can make several thread groups share
/// them).
#[derive(Debug, Clone)]
pub(crate) struct SigHandlers(pub [SigAction; Signal::MAX as usize]);

impl Default for SigHandlers {
    fn default() -> Self {
        SigHandlers([SigAction::default(); Signal::MAX as usize])
    }
}

impl SigHandlers {
    /// The disposition of a signal.
    pub fn get(&self, sig: Signal) -> SigAction {
        self.0[sig.index()]
    }

    /// Changes the disposition of a signal.
    pub fn set(&mut self, sig: Signal, act: SigAction) {
        self.0[sig.index()] = act;
    }

    /// Whether the signal is currently discarded.
    pub fn ignores(&self, sig: Signal) -> bool {
        match self.get(sig).handler {
            SigAction::IGNORE => true,
            SigAction::DEFAULT => sig.ignored_by_default(),
            _ => false,
        }
    }

    /// execve: signals with handlers revert to the default, ignored signals stay ignored.
    pub fn reset_on_exec(&mut self) {
        for act in &mut self.0 {
            let ignored = act.handler == SigAction::IGNORE;
            *act = SigAction::default();
            if ignored {
                act.handler = SigAction::IGNORE;
            }
        }
    }
}

