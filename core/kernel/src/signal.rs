/// What a synchronous exception is called in its report ([`show_unhandled`]): the strings arm64
/// Linux's handlers pass to `arm64_force_sig_fault`. Aborts are named by their fault status code
/// ([`abort_name`]).
pub(crate) mod trap {
    /// `do_undefinstr`, through `force_signal_inject`.
    pub const UNDEFINED: &str = "undefined instruction";
    /// `brk_handler` and `single_step_handler`, through `send_user_sigtrap`.
    pub const DEBUG: &str = "User debug trap";
    /// `ptrace_hbptriggered`.
    pub const HW_BREAKPOINT: &str = "Hardware breakpoint trap (ptrace)";
    /// `do_sp_pc_abort`.
    pub const SP_PC_ALIGNMENT: &str = "SP/PC alignment exception";
    /// `arm64_notify_segfault` (a bad rt_sigreturn frame).
    pub const ILLEGAL_ACCESS: &str = "illegal memory access";
}

/// The sysctl that turns the reports on ([`show_unhandled`]), as a path relative to `/proc`.
pub(crate) const EXCEPTION_TRACE: &[u8] = b"sys/debug/exception-trace";

/// arm64 Linux 6.1's `arm64_show_signal`, called just before a synchronous exception's signal is
/// forced: while `debug.exception-trace` is non-zero and the signal will go unhandled (its handler
/// is the default or ignored, which forcing resets, and no tracer decides), the kernel log gets
/// `comm[tid]: unhandled exception: `, the exception class and `esr` when it is not 0, `what`, and
/// the file mapped at the pc or above it, then the registers (`__show_regs`). At most 10 reports
/// pass per 5 seconds across the kernel. Linux also reports every exception of the initial pid
/// namespace's init, which in Tuxport is not guest code.
pub(crate) fn show_unhandled(cx: &mut Cx<'_>, cpu: &Cpu, sig: Signal, esr: u64, what: &str) {
    let handler = cx.t.group.borrow().sighand.borrow().get(sig).handler;
    if crate::pseudo::recorded_value(cx.kr(), EXCEPTION_TRACE) == 0
        || !matches!(handler, SigAction::DEFAULT | SigAction::IGNORE)
        || crate::ptrace::traced(cx.task)
    {
        return;
    }
    let (allowed, suppressed) = cx
        .k()
        .unhandled_rs
        .allow_reporting(std::time::Instant::now());
    let log = cx.kr().klog.clone();
    if suppressed > 0 {
        crate::klog::printk(
            &log,
            crate::klog::level::WARNING,
            format_args!("arm64_show_signal: {suppressed} callbacks suppressed"),
        );
    }
    if !allowed {
        return;
    }
    let comm = cx.task.comm.get();
    let comm = &comm[..comm.iter().position(|&b| b == 0).unwrap_or(comm.len())];
    let st = cpu.state();
    let mut line = comm.to_vec();
    line.extend_from_slice(format!("[{}]: unhandled exception: ", cx.tid()).as_bytes());
    if esr != 0 {
        line.extend_from_slice(format!("{}, ESR 0x{esr:016x}, ", class_name(esr)).as_bytes());
    }
    line.extend_from_slice(what.as_bytes());
    // print_vma_addr: find_vma's mapping, the first ending above the pc (which need not contain
    // it), when it maps a file
    let region = cx.mm().regions().into_iter().find(|r| r.end > st.pc);
    if let Some(r) = region
        && let (Some((_, ino)), Some(name)) = (r.file, &r.name)
    {
        let path = match cx.vfs() {
            Ok(vfs) => crate::pseudo::mark_deleted(vfs.store(), ino, name.to_vec()),
            Err(_) => name.to_vec(),
        };
        let base = path.rsplit(|&b| b == b'/').next().unwrap_or(&path);
        line.extend_from_slice(b" in ");
        line.extend_from_slice(base);
        line.extend_from_slice(format!("[{:x}+{:x}]", r.start, r.end - r.start).as_bytes());
    }
    line.push(b'\n');
    crate::klog::emit(&log, 0, crate::klog::level::INFO, &line);
    // __show_regs prints at KERN_DEFAULT, stored as default_message_loglevel; the CPU is the one
    // getcpu reports
    let level = cx.kr().printk[1] as u8 & 7;
    let cpu_nr = cx.task.affinity.get().trailing_zeros().min(63);
    let mut head = format!("CPU: {cpu_nr} PID: {} Comm: ", cx.tid()).into_bytes();
    head.extend_from_slice(comm);
    head.extend_from_slice(
        format!(" {} 6.1.0-tuxport #1\n", tainted_text(cx.kr().tainted)).as_bytes(),
    );
    crate::klog::emit(&log, 0, level, &head);
    for text in show_regs(crate::ptrace::pstate_of(st), &st.x, st.sp, st.pc) {
        crate::klog::emit(&log, 0, level, text.as_bytes());
    }
}

/// `__show_regs` for an AArch64 user thread, after the `CPU:` line: pstate, pc, lr, sp, then x29
/// down to x0, three per line. Each line ends with a newline.
fn show_regs(p: u64, x: &[u64; 31], sp: u64, pc: u64) -> Vec<String> {
    let bit = |n: u32, on: char, off: char| if p >> n & 1 != 0 { on } else { off };
    let flag = |n: u32| bit(n, '+', '-');
    let btype = ["--", "jc", "-c", "j-"][(p >> 10 & 3) as usize];
    let mut lines = vec![
        format!(
            "pstate: {p:08x} ({}{}{}{} {}{}{}{} {}PAN {}UAO {}TCO {}DIT {}SSBS BTYPE={btype})\n",
            bit(31, 'N', 'n'),
            bit(30, 'Z', 'z'),
            bit(29, 'C', 'c'),
            bit(28, 'V', 'v'),
            bit(9, 'D', 'd'),
            bit(8, 'A', 'a'),
            bit(7, 'I', 'i'),
            bit(6, 'F', 'f'),
            flag(22),
            flag(23),
            flag(25),
            flag(24),
            flag(12),
        ),
        format!("pc : {pc:016x}\n"),
        format!("lr : {:016x}\n", x[30]),
        format!("sp : {sp:016x}\n"),
    ];
    for top in (0..10).rev().map(|n| n * 3 + 2) {
        let regs: Vec<String> = (top - 2..=top)
            .rev()
            .map(|i| format!("x{i:<2}: {:016x}", x[i]))
            .collect();
        lines.push(format!("{}\n", regs.join(" ")));
    }
    lines
}

/// `esr_get_class_string`, for the exception classes Tuxport synthesizes (the others share Linux's
/// "UNRECOGNIZED EC").
fn class_name(esr: u64) -> &'static str {
    match esr >> 26 & 0x3f {
        0x00 => "Unknown/Uncategorized",
        0x20 => "IABT (lower EL)",
        0x22 => "PC Alignment",
        0x24 => "DABT (lower EL)",
        0x26 => "SP Alignment",
        0x3c => "BRK (AArch64)",
        _ => "UNRECOGNIZED EC",
    }
}

/// The name arm64 Linux's `fault_info` gives an abort's fault status code, for the codes Tuxport
/// synthesizes (crate::task) and the other translation and permission levels.
pub(crate) fn abort_name(esr: u64) -> &'static str {
    match esr & 0x3f {
        0x04 => "level 0 translation fault",
        0x05 => "level 1 translation fault",
        0x06 => "level 2 translation fault",
        0x07 => "level 3 translation fault",
        0x0d => "level 1 permission fault",
        0x0e => "level 2 permission fault",
        0x0f => "level 3 permission fault",
        0x21 => "alignment fault",
        _ => "unknown fault",
    }
}

/// `print_tainted`: "Not tainted", or "Tainted: " and one letter (or blank) for each of Linux
/// 6.1's 19 flags.
fn tainted_text(mask: u64) -> String {
    const FLAGS: [(char, char); 19] = [
        ('P', 'G'),
        ('F', ' '),
        ('S', ' '),
        ('R', ' '),
        ('M', ' '),
        ('B', ' '),
        ('U', ' '),
        ('D', ' '),
        ('A', ' '),
        ('W', ' '),
        ('C', ' '),
        ('I', ' '),
        ('O', ' '),
        ('E', ' '),
        ('L', ' '),
        ('K', ' '),
        ('X', ' '),
        ('T', ' '),
        ('N', ' '),
    ];
    if mask == 0 {
        return "Not tainted".to_owned();
    }
    let flags = FLAGS.iter().enumerate();
    let letters: String = flags
        .map(|(i, &(on, off))| if mask >> i & 1 != 0 { on } else { off })
        .collect();
    format!("Tainted: {letters}")
}

// ---- Delivering signals ----

/// Signals from synchronous exceptions are delivered first (Linux's `SYNCHRONOUS_MASK`).
const SYNCHRONOUS: u64 = (1 << (11 - 1)) // SIGSEGV
    | (1 << (7 - 1)) // SIGBUS
    | (1 << (4 - 1)) // SIGILL
    | (1 << (5 - 1)) // SIGTRAP
    | (1 << (8 - 1)) // SIGFPE
    | (1 << (31 - 1)); // SIGSYS

/// SIGKILL and SIGSTOP cannot be blocked.
pub(crate) const UNBLOCKABLE: u64 = (1 << (9 - 1)) | (1 << (19 - 1));

/// Whether there is a deliverable signal, the thread group is stopped, or the thread has been
/// asked to exit (waiting syscalls return early on this). A traced thread runs as usual once it
/// has joined a group-stop, even though the thread group is still stopped; this must also return
/// true when the tracer asks it to stop with PTRACE_INTERRUPT (crate::ptrace).
pub(crate) fn interrupted(cx: &Cx<'_>) -> bool {
    let mask = cx.task.sigmask.get();
    let g = cx.t.group.borrow();
    let pending = cx.task.pending.borrow().set() | g.pending.set();
    let t = cx.task.trace.borrow();
    let stopping = match t.tracer {
        Some(_) => t.group_stop.is_some() || t.trap,
        None => g.stopped,
    };
    cx.task.killed.get() || stopping || g.frozen || pending & !mask != 0
}

/// Before returning to the guest: handles syscall restart and delivers every deliverable signal.
///
/// `syscall` true means a syscall has just been handled and x0 is its return value.
pub(crate) fn deliver(cx: &mut Cx<'_>, cpu: &mut Cpu, syscall: bool) -> Flow {
    // (restart code, pc after the syscall): first set up for "re-execute", then changed back to
    // EINTR by the rules when there is a handler. As in Linux's do_signal, this is done before
    // checking whether the thread was killed: a killed thread stops on the svc with x0 holding the
    // original argument, and that is what core files and PTRACE_EVENT_EXIT see
    let mut restart = None;
    if syscall {
        let st = cpu.state_mut();
        let ret = st.x[0] as i64;
        if [
            Errno::ERESTARTSYS,
            Errno::ERESTARTNOINTR,
            Errno::ERESTARTNOHAND,
            Errno::ERESTART_RESTARTBLOCK,
        ]
        .iter()
        .any(|e| ret == -(e.0 as i64))
        {
            restart = Some((Errno(-ret as i32), st.pc));
            st.x[0] = st.orig_x0;
            st.pc -= 4;
        }
        cx.task.sync.entry.forget_syscall(cpu.state());
    }
    if cx.task.killed.get() {
        return Flow::Exit;
    }
    let mut handled = false;
    loop {
        // The thread group is stopped (by another thread, or by a stop signal dequeued just
        // below): stop together before returning to the guest. A traced thread stops in a
        // ptrace-stop and reports to the tracer; one the tracer asked to stop with
        // PTRACE_INTERRUPT, or one that became traced while stopped, also stops here
        // (crate::ptrace). As in Linux's get_signal, this is done before each signal is dequeued:
        // a thread PTRACE_ATTACHed while stopped first reports the group-stop, then the SIGSTOP
        // that ATTACH sent
        if let Flow::Exit = wait_while_stopped(cx) {
            return Flow::Exit;
        }
        if crate::ptrace::traced(cx.task)
            && (!crate::ptrace::group_stop(cx, cpu) || !crate::ptrace::trap(cx, cpu))
        {
            return Flow::Exit;
        }
        let Some((sig, info)) = dequeue(cx) else {
            break;
        };
        // A traced thread first stops so the tracer can look (signal-delivery stop), and the
        // tracer can replace the signal or not deliver it; SIGKILL never comes through here, and
        // signals forced by seccomp do not stop either (SA_IMMUTABLE)
        let immutable = cx.t.group.borrow().sighand.borrow().get(sig).immutable;
        let (sig, info) = if crate::ptrace::traced(cx.task) && !immutable {
            match crate::ptrace::signal_stop(cx, cpu, sig, info) {
                Ok(Some(delivered)) => delivered,
                Ok(None) => continue,
                Err(()) => return Flow::Exit,
            }
        } else {
            (sig, info)
        };
        let act = cx.t.group.borrow().sighand.borrow().get(sig);
        // Process 1 of a pid namespace: the only default-handled signals are SIGKILL and SIGSTOP
        // (already filtered when sent) and forced synchronous signals ([`force`])
        let unkillable = unkillable(&cx.t.group.borrow()) && sig != Signal::STOP;
        match act.handler {
            SigAction::IGNORE => continue,
            SigAction::DEFAULT if sig.ignored_by_default() || unkillable => continue,
            SigAction::DEFAULT if sig.is_stop() => {
                // Orphaned process groups do not respond to terminal-generated stop signals
                // (except SIGSTOP)
                let pgid = cx.t.group.borrow().pgid;
                if sig != Signal::STOP && pgrp_orphaned(cx.kr(), pgid) {
                    continue;
                }
                group_stop(cx, sig);
                continue;
            }
            SigAction::DEFAULT => {
                let mut status = ExitStatus::Signaled {
                    signal: sig,
                    pc: matches!(info.fields, InfoFields::Fault { .. }).then_some(cpu.state().pc),
                    fault_addr: info
                        .fault_addr()
                        .filter(|_| sig == Signal::SEGV || sig == Signal::BUS),
                    core_dumped: false,
                };
                let group = cx.t.group.clone();
                // When another thread is already ending the whole process (exit_group, another
                // fatal signal), no core is written
                let first = group.borrow().exiting.is_none();
                group_exit(cx.k(), &group, status);
                if first
                    && crate::coredump::dumps_core(sig)
                    && crate::coredump::dump(cx, cpu.state(), sig, &info)
                    && let ExitStatus::Signaled { core_dumped, .. } = &mut status
                {
                    *core_dumped = true;
                    group.borrow_mut().exiting = Some(status);
                }
                crate::ptrace::exit(cx, cpu, status);
                return Flow::Exit;
            }
            _ => {}
        }
        // When the tracer has changed the pc, restart no longer applies (as in Linux's
        // do_signal)
        if let (false, Some((code, cont))) = (handled, restart)
            && cpu.state().pc == cont - 4
        {
            let to_eintr = code == Errno::ERESTARTNOHAND
                || code == Errno::ERESTART_RESTARTBLOCK
                || (code == Errno::ERESTARTSYS && act.flags & sa::RESTART == 0);
            if to_eintr {
                let st = cpu.state_mut();
                st.x[0] = Errno::EINTR.to_syscall_return();
                st.pc = cont;
            }
        }
        // Decided by the first signal taken, even if its frame cannot be written (Linux's do_signal
        // forgets the syscall before handling it)
        restart = None;
        // The mask temporarily swapped by sigsuspend or ppoll: the frame saves the original,
        // restored when the handler returns
        let swapped = cx.task.saved_sigmask.take();
        let saved = swapped.unwrap_or(cx.task.sigmask.get());
        if setup_frame(cx, cpu, sig, &info, &act, saved).is_err() {
            // Linux's force_sigsegv: a SIGSEGV is forced on the thread instead, delivered next
            // (to a handler on an alternate stack, or ending the process with a core and the
            // tracer's stops); one whose own frame cannot be written ends the process. The mask
            // is unchanged, and a mask swapped by sigsuspend or ppoll still waits to be restored
            crate::debug::log(format_args!("cannot set up the frame for {sig}"));
            cx.task.saved_sigmask.set(swapped);
            if sig == Signal::SEGV {
                force_fatal(cx, Signal::SEGV, SigInfo::kernel());
            } else {
                force(cx, Signal::SEGV, SigInfo::kernel());
            }
            continue;
        }
        let mut mask = cx.task.sigmask.get() | act.mask;
        if act.flags & sa::NODEFER == 0 {
            mask |= sig.bit();
        }
        cx.task.sigmask.set(mask & !UNBLOCKABLE);
        if act.flags & sa::RESETHAND != 0 {
            // As on Linux, only the handler goes back to SIG_DFL; flags and mask stay unchanged
            let group = cx.t.group.borrow();
            let reset = SigAction {
                handler: SigAction::DEFAULT,
                ..act
            };
            group.sighand.borrow_mut().set(sig, reset);
        }
        handled = true;
    }
    if !handled && let Some(saved) = cx.task.saved_sigmask.take() {
        cx.task.sigmask.set(saved);
    }
    // Signals sent to the process that this thread now blocks (sigprocmask, a handler's mask, a
    // restored mask) and has not taken: another thread must take them
    let blocked = cx.t.group.borrow().pending.set() & cx.task.sigmask.get();
    if blocked != 0 {
        retarget(cx.kr(), &cx.t.group, Some(cx.tid()), blocked);
    }
    // PTRACE_SINGLESTEP entered a handler: as on arm64 Linux (tracehook_signal_handler after
    // user_fastforward_single_step), stop at the handler's first instruction before executing it
    if handled
        && cx.task.stepping.load(std::sync::atomic::Ordering::Relaxed)
        && !crate::ptrace::handler_entered(cx, cpu)
    {
        return Flow::Exit;
    }
    // No handler interrupted: the svc being re-executed becomes restart_syscall, which continues
    // the remaining part
    if !handled
        && let Some((Errno::ERESTART_RESTARTBLOCK, cont)) = restart
        && cpu.state().pc == cont - 4
    {
        cpu.state_mut().x[8] = super::syscall::NR_RESTART_SYSCALL;
    }
    Flow::Continue
}

/// Signals in `set` are pending for the whole process `group` but the thread `except` will not
/// take them (it blocks them, or is exiting): wakes a thread that does not block each, as Linux's
/// `retarget_shared_pending` does, so they do not wait for the thread chosen when they were sent.
pub(crate) fn retarget(
    k: &Kernel,
    group: &RefCell<ThreadGroup>,
    except: Option<Tid>,
    mut set: u64,
) {
    let threads = group.borrow().threads.clone();
    for tid in threads {
        if set == 0 {
            break;
        }
        let Some(t) = k.tasks.get(&tid).filter(|_| Some(tid) != except) else {
            continue;
        };
        let takes = set & !t.sigmask.get();
        if takes != 0 {
            wake(t);
            set &= !takes;
        }
    }
}

/// While the thread group is stopped, waits here until SIGCONT or until killed. A thread that
/// becomes ptrace-traced while stopped also leaves, to stop in a ptrace-stop instead
/// ([`deliver`]). While its cgroup is frozen it also waits here until thawed (Linux's
/// `do_freezer_trap`), traced threads too; meanwhile it is recorded as stopped (`cgroup.events`).
fn wait_while_stopped(cx: &mut Cx<'_>) -> Flow {
    let flow = loop {
        if cx.task.killed.get() {
            break Flow::Exit;
        }
        let (stopped, frozen) = {
            let g = cx.t.group.borrow();
            (g.stopped && !crate::ptrace::traced(cx.task), g.frozen)
        };
        if !stopped && !frozen {
            break Flow::Continue;
        }
        // The last thread stopping completes the freeze (cgroup.events' frozen)
        if frozen {
            crate::cgroup::enter_frozen(cx);
            crate::cgroup::notify_changes(cx.k());
        } else {
            cx.task.frozen.set(false);
        }
        // Only SIGCONT, SIGKILL and thawing can make it leave here, so other signals are not
        // checked
        let _ = cx.wait(None, &mut []);
    };
    // A killed task still counts as frozen. Otherwise its group has thawed.
    cx.task.frozen.set(false);
    flow
}

/// Takes the next unblocked pending signal: the thread's own first, then the thread group's.
fn dequeue(cx: &mut Cx<'_>) -> Option<(Signal, SigInfo)> {
    take(cx, !cx.task.sigmask.get())
}

/// Takes one pending signal in `set`, the thread's own first (sigtimedwait ignores the mask).
pub(crate) fn take(cx: &mut Cx<'_>, set: u64) -> Option<(Signal, SigInfo)> {
    let taken = {
        let mut own = cx.task.pending.borrow_mut();
        let mut g = cx.t.group.borrow_mut();
        if own.set() & set != 0 {
            let sig = pick(own.set() & set);
            Some((sig, own.take(sig)))
        } else if g.pending.set() & set != 0 {
            let sig = pick(g.pending.set() & set);
            Some((sig, g.pending.take(sig)))
        } else {
            None
        }
    };
    // A POSIX timer's signal has been delivered: from now on timer_getoverrun reports its
    // accumulated overrun count
    if let Some((_, info)) = &taken
        && let InfoFields::Timer { id, overrun, .. } = info.fields
        && info.code == code::SI_TIMER
        && let Some(t) = cx.t.group.borrow_mut().posix_timers.get_mut(&id)
    {
        t.overrun = overrun;
    }
    taken
}

fn pick(set: u64) -> Signal {
    let sync = set & SYNCHRONOUS;
    let set = if sync != 0 { sync } else { set };
    Signal::new(set.trailing_zeros() as i32 + 1).unwrap()
}

/// An orphaned process group: no process in the group has a parent in another process group of
/// the same session. Once such a group is stopped nobody can continue it, so terminal-generated
/// stop signals have no effect on it.
pub(crate) fn pgrp_orphaned(k: &Kernel, pgid: Tid) -> bool {
    !k.groups.values().any(|g| {
        let g = g.borrow();
        g.pgid == pgid
            && g.zombie.is_none()
            && k.groups.get(&g.ppid).is_some_and(|p| {
                let p = p.borrow();
                p.pgid != pgid && p.sid == g.sid
            })
    })
}

/// Stops the whole thread group (the default action of stop signals): notifies the parent and
/// kicks the other threads so that they stop too. Traced threads (including this one) record that
/// they must join this group-stop (crate::ptrace).
fn group_stop(cx: &mut Cx<'_>, sig: Signal) {
    let group = cx.t.group.clone();
    let threads = {
        let mut g = group.borrow_mut();
        g.stopped = true;
        g.stop_signal = sig;
        g.stop_report = Some(sig);
        g.cont_report = false;
        g.threads.clone()
    };
    for t in threads.iter().filter_map(|t| cx.kr().tasks.get(t)) {
        {
            let mut trace = t.trace.borrow_mut();
            if trace.tracer.is_some() {
                trace.group_stop = Some(sig);
            }
        }
        if !Rc::ptr_eq(t, cx.task) {
            wake(t);
        }
    }
    notify_parent(cx.kr(), &group, code::CLD_STOPPED, sig.number());
}

// ---- Signal frames ----

/// sigaltstack ss_flags.
pub(crate) mod ss {
    /// Currently running on the alternate stack.
    pub const ONSTACK: u32 = 1;
    /// The alternate stack is disabled.
    pub const DISABLE: u32 = 2;
    /// Disable the alternate stack automatically when switching to it.
    pub const AUTODISARM: u32 = 1 << 31;
}

/// arm64 uapi's `MINSIGSTKSZ`: the smallest alternate stack sigaltstack accepts.
pub(crate) const MINSIGSTKSZ: u64 = 5120;

/// A thread's alternate signal stack.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct AltStack {
    pub sp: u64,
    pub size: u64,
    /// Only `SS_DISABLE` and `SS_AUTODISARM`.
    pub flags: u32,
}

impl Default for AltStack {
    fn default() -> Self {
        AltStack {
            sp: 0,
            size: 0,
            flags: ss::DISABLE,
        }
    }
}

impl AltStack {
    /// Whether `sp` is on the alternate stack (Linux's `on_sig_stack`).
    pub fn on_stack(&self, sp: u64) -> bool {
        if self.flags & ss::AUTODISARM != 0 {
            return false;
        }
        sp > self.sp && sp - self.sp <= self.size
    }

    /// The ss_flags reported to the guest (Linux's `sas_ss_flags` plus `SS_AUTODISARM`).
    pub fn reported_flags(&self, sp: u64) -> u32 {
        let state = if self.size == 0 {
            ss::DISABLE
        } else if self.on_stack(sp) {
            ss::ONSTACK
        } else {
            0
        };
        state | (self.flags & ss::AUTODISARM)
    }

    /// Changes it by the rules of sigaltstack(2); unchanged when Err is returned.
    pub fn change(&mut self, cur_sp: u64, sp: u64, flags: u32, size: u64) -> Result<(), Errno> {
        if self.on_stack(cur_sp) {
            return Err(Errno::EPERM);
        }
        let mode = flags & !ss::AUTODISARM;
        match mode {
            ss::DISABLE => *self = AltStack::default(),
            0 | ss::ONSTACK => {
                if size < MINSIGSTKSZ {
                    return Err(Errno::ENOMEM);
                }
                *self = AltStack {
                    sp,
                    size,
                    flags: flags & ss::AUTODISARM,
                };
            }
            _ => return Err(Errno::EINVAL),
        }
        Ok(())
    }
}

const UC: usize = 128;
const UC_STACK: usize = UC + 16;
const UC_SIGMASK: usize = UC + 40;
const MCONTEXT: usize = UC + 176;
const FAULT_ADDRESS: usize = MCONTEXT;
const REGS: usize = MCONTEXT + 8;
const SP: usize = MCONTEXT + 256;
const PC: usize = MCONTEXT + 264;
const PSTATE: usize = MCONTEXT + 272;
const RESERVED: usize = MCONTEXT + 288;
const RESERVED_SIZE: usize = 4096;
/// `sizeof(struct rt_sigframe)`.
const FRAME_SIZE: usize = RESERVED + RESERVED_SIZE;
/// The `struct frame_record` above the frame.
const FRAME_RECORD: usize = 16;
/// The `AT_MINSIGSTKSZ` advertised to the guest: the frame and the frame record plus up to 16
/// bytes of alignment, the same value arm64 Linux computes without SVE/SME.
pub(crate) const MIN_SIGSTKSZ: u64 = (FRAME_SIZE + FRAME_RECORD + 16) as u64;

const FPSIMD_MAGIC: u32 = 0x4650_8001;
const FPSIMD_SIZE: usize = 528;
const ESR_MAGIC: u32 = 0x4553_5201;
const ESR_SIZE: usize = 16;
/// The exception level and AArch32 bits of pstate: in a signal frame they must be EL0t, AArch64.
const PSTATE_MODE: u64 = 0x1f;

/// Builds the signal frame on the guest stack and makes the CPU start executing the handler.
fn setup_frame(
    cx: &mut Cx<'_>,
    cpu: &mut Cpu,
    sig: Signal,
    info: &SigInfo,
    act: &SigAction,
    saved_mask: u64,
) -> Result<(), Errno> {
    let alt = cx.t.altstack;
    let st = cpu.state_mut();
    let mut top = st.sp;
    if act.flags & sa::ONSTACK != 0 && alt.size != 0 && !alt.on_stack(st.sp) {
        top = alt.sp.wrapping_add(alt.size);
    }
    let record = top.checked_sub(FRAME_RECORD as u64).ok_or(Errno::EFAULT)? & !15;
    let frame = record.checked_sub(FRAME_SIZE as u64).ok_or(Errno::EFAULT)?;

    let mut b = vec![0u8; FRAME_SIZE + FRAME_RECORD];
    b[..128].copy_from_slice(&info.encode(sig));
    // uc_flags and uc_link are 0
    w64(&mut b, UC_STACK, alt.sp);
    w32(&mut b, UC_STACK + 8, alt.reported_flags(st.sp));
    w64(&mut b, UC_STACK + 16, alt.size);
    w64(&mut b, UC_SIGMASK, saved_mask);
    w64(&mut b, FAULT_ADDRESS, info.fault_addr().unwrap_or(0));
    for (i, &x) in st.x.iter().enumerate() {
        w64(&mut b, REGS + 8 * i, x);
    }
    w64(&mut b, SP, st.sp);
    w64(&mut b, PC, st.pc);
    // The handler still runs with the DIT it was interrupted with (Linux's setup_return clears
    // only BTYPE and TCO)
    w64(&mut b, PSTATE, crate::ptrace::pstate_of(st));
    // __reserved: fpsimd_context, an optional esr_context, and finally a null record
    let mut off = RESERVED;
    w32(&mut b, off, FPSIMD_MAGIC);
    w32(&mut b, off + 4, FPSIMD_SIZE as u32);
    w32(&mut b, off + 8, st.fpsr as u32);
    w32(&mut b, off + 12, st.fpcr as u32);
    for (i, v) in st.v.iter().enumerate() {
        w64(&mut b, off + 16 + 16 * i, v[0]);
        w64(&mut b, off + 24 + 16 * i, v[1]);
    }
    off += FPSIMD_SIZE;
    if info.esr != 0 {
        w32(&mut b, off, ESR_MAGIC);
        w32(&mut b, off + 4, ESR_SIZE as u32);
        w64(&mut b, off + 8, info.esr);
    }
    // Frame record: lets stack unwinding get past the signal frame
    w64(&mut b, FRAME_SIZE, st.x[29]);
    w64(&mut b, FRAME_SIZE + 8, st.x[30]);
    // When the frame falls below the bottom of the stack, grow the stack first, as Linux's fault
    // handling does
    cx.grow_stack(frame);
    cx.mm().write(UserSlice::new(frame, b.len()), &b)?;

    if alt.flags & ss::AUTODISARM != 0 {
        cx.t.altstack = AltStack::default();
    }
    let restorer = if act.flags & sa::RESTORER != 0 {
        act.restorer
    } else {
        cx.mm().vdso + crate::vdso::sigreturn_offset()
    };
    st.x[0] = sig.number() as u64;
    if act.flags & sa::SIGINFO != 0 {
        st.x[1] = frame;
        st.x[2] = frame + UC as u64;
    }
    st.sp = frame;
    st.x[29] = record;
    st.x[30] = restorer;
    st.pc = act.handler;
    Ok(())
}

fn w32(b: &mut [u8], off: usize, v: u32) {
    b[off..off + 4].copy_from_slice(&v.to_le_bytes());
}

fn w64(b: &mut [u8], off: usize, v: u64) {
    b[off..off + 8].copy_from_slice(&v.to_le_bytes());
}

/// rt_sigreturn: restores registers, the signal mask and the alternate stack from the signal
/// frame on the stack. An invalid frame changes nothing, returns 0 and forces a SIGSEGV at the
/// stack pointer (arm64's `arm64_notify_segfault`), which a handler may catch.
pub(crate) fn sigreturn(cx: &mut Cx<'_>, cpu: &mut Cpu) -> Flow {
    if restore_frame(cx, cpu).is_err() {
        crate::debug::log(format_args!("rt_sigreturn: bad signal frame"));
        let sp = cpu.state().sp;
        // SEGV_MAPERR only when no mapping ends above the address (Linux's find_vma)
        let code = if cx.mm().mapped_above(sp) {
            code::SEGV_ACCERR
        } else {
            code::SEGV_MAPERR
        };
        show_unhandled(cx, cpu, Signal::SEGV, 0, trap::ILLEGAL_ACCESS);
        force(cx, Signal::SEGV, SigInfo::fault(code, sp, 0));
        cpu.state_mut().x[0] = 0;
    }
    // PTRACE_SYSCALL: stop at exit, and the tracer sees the restored registers (crate::ptrace)
    if crate::ptrace::traced(cx.task) && !crate::ptrace::syscall_exit(cx, cpu) {
        return Flow::Exit;
    }
    // The restored mask may have unblocked pending signals; x0 is the restored value, not
    // treated as a syscall return value
    deliver(cx, cpu, false)
}

fn restore_frame(cx: &mut Cx<'_>, cpu: &mut Cpu) -> Result<(), Errno> {
    let frame = cpu.state().sp;
    if !frame.is_multiple_of(16) {
        return Err(Errno::EFAULT);
    }
    let mut b = vec![0u8; FRAME_SIZE];
    cx.mm().read(UserSlice::new(frame, FRAME_SIZE), &mut b)?;
    let pstate = r64(&b, PSTATE);
    if pstate & PSTATE_MODE != 0 {
        return Err(Errno::EINVAL);
    }
    // Parse the records in __reserved first, and change no state until the whole frame is known
    // to be valid
    let mut fpsimd = None;
    let mut off = 0;
    loop {
        if off + 8 > RESERVED_SIZE {
            return Err(Errno::EINVAL);
        }
        let magic = r32(&b, RESERVED + off);
        let size = r32(&b, RESERVED + off + 4) as usize;
        if magic == 0 && size == 0 {
            break;
        }
        if size < 8 || !size.is_multiple_of(16) || off + size > RESERVED_SIZE {
            return Err(Errno::EINVAL);
        }
        match magic {
            FPSIMD_MAGIC if size == FPSIMD_SIZE && fpsimd.is_none() => {
                fpsimd = Some(RESERVED + off);
            }
            ESR_MAGIC => {}
            _ => return Err(Errno::EINVAL),
        }
        off += size;
    }
    let fp = fpsimd.ok_or(Errno::EINVAL)?;

    let st = cpu.state_mut();
    for (i, x) in st.x.iter_mut().enumerate() {
        *x = r64(&b, REGS + 8 * i);
    }
    st.sp = r64(&b, SP);
    st.pc = r64(&b, PC);
    crate::ptrace::set_pstate(st, pstate);
    st.fpsr = r32(&b, fp + 8) as u64;
    st.fpcr = r32(&b, fp + 12) as u64;
    for (i, v) in st.v.iter_mut().enumerate() {
        v[0] = r64(&b, fp + 16 + 16 * i);
        v[1] = r64(&b, fp + 24 + 16 * i);
    }
    let sp = st.sp;
    cx.task.sigmask.set(r64(&b, UC_SIGMASK) & !UNBLOCKABLE);
    // As with Linux's restore_altstack, a failed change of the alternate stack leaves it as it was
    let _ = cx.t.altstack.change(
        sp,
        r64(&b, UC_STACK),
        r32(&b, UC_STACK + 8),
        r64(&b, UC_STACK + 16),
    );
    Ok(())
}

fn r32(b: &[u8], off: usize) -> u32 {
    u32::from_le_bytes(b[off..off + 4].try_into().unwrap())
}

fn r64(b: &[u8], off: usize) -> u64 {
    u64::from_le_bytes(b[off..off + 8].try_into().unwrap())
}

