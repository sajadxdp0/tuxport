//! Signals (the kernel/signal map): generation, delivery, signal frames and rt_sigreturn.
//!
//! Each thread has its own pending set and signal mask; signals sent to a whole process are
//! pending on the thread group and handled by the first thread that does not block them.
//! Dispositions ([`SigHandlers`]) belong to the thread group. Signals are delivered before
//! returning to the guest: after a syscall, after an interruption by a kick, after a synchronous
//! exception.
//!
//! The signal frame copies Linux arm64's `struct rt_sigframe` byte for byte: siginfo, ucontext
//! (sigcontext followed by fpsimd_context, plus esr_context for synchronous exceptions, ending with
//! a null record), and above the frame a `{fp, lr}` frame record. The syscall restart rules are
//! taken from arm64's `do_signal`.

