/// The siginfo fields that vary with si_code.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub(crate) enum InfoFields {
    /// No extra fields.
    #[default]
    None,
    /// kill, tkill: the sender.
    Kill { pid: Tid, uid: u32 },
    /// SIGCHLD: the child and its status.
    Child { pid: Tid, uid: u32, status: i32 },
    /// sigqueue (rt_sigqueueinfo): the sender and the attached value.
    Queue { pid: Tid, uid: u32, value: u64 },
    /// POSIX timer expiry: the timer id, the overrun count and `sigev_value`.
    Timer { id: i32, overrun: u32, value: u64 },
    /// Synchronous exception: the fault address.
    Fault { addr: u64 },
    /// Signal-driven I/O (`F_SETSIG`): the ready events and the fd.
    Poll { band: i64, fd: i32 },
    /// seccomp's SIGSYS: the data from the filter (`si_errno`), the address after the svc, and the
    /// syscall's number and architecture.
    Sys {
        errno: i32,
        call_addr: u64,
        syscall: i32,
        arch: u32,
    },
    /// Given by a tracer with PTRACE_SETSIGINFO: the part of `siginfo_t` after si_code, delivered
    /// as is.
    Raw([u8; 112]),
    /// Given by the sender (rt_sigqueueinfo, rt_tgsigqueueinfo, pidfd_send_signal): `si_errno`
    /// and the fields Linux's `kernel_siginfo` keeps, delivered as given apart from si_pid and
    /// si_uid, which are converted like a sigqueue's.
    User {
        errno: i32,
        pid: Tid,
        uid: u32,
        /// Bytes 24 to 48 of `siginfo_t` (`si_value` first).
        rest: [u8; 24],
    },
}

/// The siginfo attached to a pending signal.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub(crate) struct SigInfo {
    pub code: i32,
    pub fields: InfoFields,
    /// The ESR of a synchronous exception, put into the signal frame's esr_context; 0 means none
    /// (as on Linux, breakpoints and signals that are not synchronous exceptions have none).
    pub esr: u64,
    /// The process that sent it (a global id, not encoded); 0 for kernel-generated ones. si_pid is
    /// the id the sender itself sees, changed to 0 when the target's pid namespace cannot see the
    /// sender ([`for_target`]).
    pub sender: Tid,
    /// Which user namespace si_uid was filled in for (an id; 0 means no further conversion), and
    /// the matching kernel ID there (`u32::MAX` when unmappable): when the target is in another
    /// user namespace, it is converted for the target ([`SigInfo::sent_by`]).
    pub uid_ns: u64,
    pub kuid: u32,
}

impl SigInfo {
    /// A signal sent with kill(2) or tkill(2) by process `pid`, whose real user ID is `uid`.
    pub fn kill(code: i32, pid: Tid, uid: u32) -> SigInfo {
        SigInfo {
            code,
            fields: InfoFields::Kill { pid, uid },
            ..SigInfo::default()
        }
    }

    /// A signal the kernel generates itself (SIGPIPE, for example).
    pub fn kernel() -> SigInfo {
        SigInfo {
            code: code::SI_KERNEL,
            ..SigInfo::default()
        }
    }

    /// A synchronous exception.
    pub fn fault(code: i32, addr: u64, esr: u64) -> SigInfo {
        SigInfo {
            code,
            fields: InfoFields::Fault { addr },
            esr,
            ..SigInfo::default()
        }
    }

    /// The SIGCHLD sent to the parent when a child exits. `uid` is the child's real user ID as
    /// seen in the parent's namespace.
    pub fn child(pid: Tid, uid: u32, status: ExitStatus) -> SigInfo {
        let (code, status) = match status {
            ExitStatus::Exited(c) => (code::CLD_EXITED, c),
            ExitStatus::Signaled {
                signal,
                core_dumped,
                ..
            } => {
                let code = if core_dumped {
                    code::CLD_DUMPED
                } else {
                    code::CLD_KILLED
                };
                (code, signal.number())
            }
        };
        Self::child_event(pid, uid, code, status)
    }

    /// The SIGCHLD sent to the parent when a child's state changes (`CLD_*`). `uid` as in
    /// [`SigInfo::child`].
    pub fn child_event(pid: Tid, uid: u32, code: i32, status: i32) -> SigInfo {
        SigInfo {
            code,
            fields: InfoFields::Child { pid, uid, status },
            ..SigInfo::default()
        }
    }

    /// A siginfo encoded as `siginfo_t` (given by a tracer); the signal number is given
    /// separately.
    pub fn from_raw(b: &[u8; 128]) -> SigInfo {
        SigInfo {
            code: i32::from_le_bytes(b[8..12].try_into().unwrap()),
            fields: InfoFields::Raw(b[16..].try_into().unwrap()),
            ..SigInfo::default()
        }
    }

    /// si_uid is filled in by sender `sender` for its own user namespace (Linux's
    /// `send_signal_locked`): when the target is in another user namespace, it is first mapped
    /// back to a kernel ID in the sender's namespace (unmappable ones become an invalid ID), then
    /// converted for the target's namespace ([`for_target`]), where the invalid ID is 65534.
    /// Within the same namespace it is delivered as is (so is a value given by sigqueue).
    pub fn sent_by(mut self, sender: &Cred) -> SigInfo {
        if let Some(uid) = self.uid() {
            self.uid_ns = sender.user_ns.id;
            self.kuid = sender.uid_in(uid).unwrap_or(u32::MAX);
        }
        self
    }

    /// The kinds that carry si_uid (Linux's `has_si_pid_and_uid`: the kill, SIGCHLD and real-time
    /// signal layouts).
    fn uid(&self) -> Option<u32> {
        match self.fields {
            InfoFields::Kill { uid, .. }
            | InfoFields::Child { uid, .. }
            | InfoFields::Queue { uid, .. }
            | InfoFields::User { uid, .. } => Some(uid),
            _ => None,
        }
    }

    /// Sent by process `sender` (a global id).
    pub fn from(self, sender: Tid) -> SigInfo {
        SigInfo { sender, ..self }
    }

    /// Delivered to a process with credentials `target`: converts si_uid as
    /// [`SigInfo::sent_by`] describes.
    fn retarget_uid(&mut self, target: &Cred) {
        if self.uid_ns == 0 || self.uid_ns == target.user_ns.id {
            return;
        }
        let v = target.uid_out(self.kuid);
        if let InfoFields::Kill { uid, .. }
        | InfoFields::Child { uid, .. }
        | InfoFields::Queue { uid, .. }
        | InfoFields::User { uid, .. } = &mut self.fields
        {
            *uid = v;
        }
        self.uid_ns = 0;
    }

    /// Removes the sender (writes 0 to si_pid).
    fn hide_sender(&mut self) {
        if let InfoFields::Kill { pid, .. }
        | InfoFields::Child { pid, .. }
        | InfoFields::Queue { pid, .. }
        | InfoFields::User { pid, .. } = &mut self.fields
        {
            *pid = 0;
        }
    }

    fn fault_addr(&self) -> Option<u64> {
        match self.fields {
            InfoFields::Fault { addr } => Some(addr),
            _ => None,
        }
    }

    /// Encodes as Linux's `siginfo_t` (128 bytes).
    pub fn encode(&self, sig: Signal) -> [u8; 128] {
        let mut b = [0u8; 128];
        b[..4].copy_from_slice(&sig.number().to_le_bytes());
        b[8..12].copy_from_slice(&self.code.to_le_bytes());
        match self.fields {
            InfoFields::None => {}
            InfoFields::Kill { pid, uid } => {
                b[16..20].copy_from_slice(&pid.to_le_bytes());
                b[20..24].copy_from_slice(&uid.to_le_bytes());
            }
            InfoFields::Child { pid, uid, status } => {
                b[16..20].copy_from_slice(&pid.to_le_bytes());
                b[20..24].copy_from_slice(&uid.to_le_bytes());
                b[24..28].copy_from_slice(&status.to_le_bytes());
            }
            InfoFields::Timer { id, overrun, value } => {
                b[16..20].copy_from_slice(&id.to_le_bytes());
                b[20..24].copy_from_slice(&overrun.to_le_bytes());
                b[24..32].copy_from_slice(&value.to_le_bytes());
            }
            InfoFields::Queue { pid, uid, value } => {
                b[16..20].copy_from_slice(&pid.to_le_bytes());
                b[20..24].copy_from_slice(&uid.to_le_bytes());
                b[24..32].copy_from_slice(&value.to_le_bytes());
            }
            InfoFields::Fault { addr } => b[16..24].copy_from_slice(&addr.to_le_bytes()),
            InfoFields::Poll { band, fd } => {
                b[16..24].copy_from_slice(&band.to_le_bytes());
                b[24..28].copy_from_slice(&fd.to_le_bytes());
            }
            InfoFields::Sys {
                errno,
                call_addr,
                syscall,
                arch,
            } => {
                b[4..8].copy_from_slice(&errno.to_le_bytes());
                b[16..24].copy_from_slice(&call_addr.to_le_bytes());
                b[24..28].copy_from_slice(&syscall.to_le_bytes());
                b[28..32].copy_from_slice(&arch.to_le_bytes());
            }
            InfoFields::Raw(rest) => b[16..].copy_from_slice(&rest),
            InfoFields::User {
                errno,
                pid,
                uid,
                rest,
            } => {
                b[4..8].copy_from_slice(&errno.to_le_bytes());
                b[16..20].copy_from_slice(&pid.to_le_bytes());
                b[20..24].copy_from_slice(&uid.to_le_bytes());
                b[24..48].copy_from_slice(&rest);
            }
        }
        b
    }
}

/// Pending signals (Linux's `struct sigpending`). A standard signal is pending at most once per
/// kind, and later instances are dropped, so it keeps the first one's siginfo (`legacy_queue`);
/// every instance of a real-time signal is queued and delivered in the order generated, each with
/// its own siginfo.
#[derive(Default)]
pub(crate) struct Pending {
    set: u64,
    /// The siginfo of the standard signals (1–31).
    info: [SigInfo; 31],
    /// Queued real-time signals.
    queue: VecDeque<(Signal, SigInfo)>,
    /// How many times signals became pending (a standard signal generated again while already
    /// pending does not count): as with Linux's signalfd_notify, each one makes a signalfd's
    /// `EPOLLET` fire again.
    arrivals: u64,
}

impl Pending {
    /// Makes a signal pending. With `room` false a real-time signal is no longer queued
    /// (`RLIMIT_SIGPENDING` exceeded): as on Linux, the signal is still made pending and the
    /// siginfo is dropped.
    pub fn add(&mut self, sig: Signal, info: SigInfo, room: bool) {
        let new = self.set & sig.bit() == 0;
        if sig.is_realtime() || new {
            self.arrivals += 1;
        }
        if !sig.is_realtime() {
            if new {
                self.info[sig.index()] = info;
            }
        } else if room {
            self.queue.push_back((sig, info));
        }
        self.set |= sig.bit();
    }

    /// Takes one `sig`. For a real-time signal this is the earliest queued one, and the signal
    /// stays pending while more of the same kind are queued; for one that was never queued, the
    /// siginfo is empty (si_code SI_USER), as on Linux.
    pub fn take(&mut self, sig: Signal) -> SigInfo {
        if !sig.is_realtime() {
            self.set &= !sig.bit();
            return self.info[sig.index()];
        }
        let mut same = self
            .queue
            .iter()
            .enumerate()
            .filter(|(_, (s, _))| *s == sig);
        let (first, more) = (same.next().map(|(i, _)| i), same.next().is_some());
        if !more {
            self.set &= !sig.bit();
        }
        first
            .and_then(|i| self.queue.remove(i))
            .map_or_else(SigInfo::default, |(_, info)| info)
    }

    /// Discards the signals in `mask`, including queued ones.
    pub fn discard(&mut self, mask: u64) {
        self.set &= !mask;
        self.queue.retain(|(s, _)| mask & s.bit() == 0);
    }

    /// The siginfo of a pending `sig` (a timer adds its overrun count to the signal it sent last).
    pub fn infos_mut(&mut self, sig: Signal) -> impl Iterator<Item = &mut SigInfo> {
        let Pending {
            set, info, queue, ..
        } = self;
        let standard =
            (!sig.is_realtime() && *set & sig.bit() != 0).then(|| &mut info[sig.index()]);
        standard.into_iter().chain(
            queue
                .iter_mut()
                .filter(move |(s, _)| *s == sig)
                .map(|(_, info)| info),
        )
    }

    /// The set of pending signals.
    pub fn set(&self) -> u64 {
        self.set
    }

    /// How many times signals became pending.
    pub fn arrivals(&self) -> u64 {
        self.arrivals
    }

    /// The number of queued real-time signals.
    pub fn queued(&self) -> usize {
        self.queue.len()
    }
}

// ---- Generating signals ----

/// Sends a signal to one thread (tkill, SIGPIPE and so on).
pub(crate) fn send_to_task(k: &Kernel, task: &Task, sig: Signal, info: SigInfo) {
    let Some(group) = k.groups.get(&task.tgid).cloned() else {
        return;
    };
    let blocked = task.sigmask.get() & sig.bit() != 0;
    let traced = crate::ptrace::traced(task);
    let target = for_target(&group.borrow(), sig, info, blocked, traced);
    if sig == Signal::KILL {
        if target.is_some() {
            group_exit(k, &group, killed_by(sig));
        }
        return;
    }
    // Side effects such as SIGCONT resuming the process happen even if the signal is then dropped
    // (Linux's prepare_signal)
    prepare(k, &group, sig);
    let Some(info) = target else {
        return;
    };
    // A blocked signal is made pending even if currently ignored: the disposition may change
    // before it is unblocked. It is also made pending for a traced thread, since the tracer must
    // see it
    if !blocked && group.borrow().sighand.borrow().ignores(sig) && !traced {
        return;
    }
    let room = sig.is_realtime() && queue_room(k, &group.borrow());
    task.pending.borrow_mut().add(sig, info, room);
    if !blocked {
        wake(task);
    } else {
        // Blocked signals are exactly what sigtimedwait, signalfd and the like wait for: wake
        // only those waiting for them (wake::SIGNAL)
        request_wake_on(wake::SIGNAL);
    }
}

/// Sends a signal to every process in a process group (terminal-generated signals, kill with a
/// negative pid).
pub(crate) fn send_to_pgrp(k: &Kernel, pgid: Tid, sig: Signal, info: SigInfo) {
    let members: Vec<Tid> = k
        .groups
        .values()
        .filter(|g| g.borrow().pgid == pgid)
        .map(|g| g.borrow().tgid)
        .collect();
    for tgid in members {
        send_to_group(k, tgid, sig, info);
    }
}

/// Sends a signal to a whole thread group (kill). Does nothing when the target is a zombie.
pub(crate) fn send_to_group(k: &Kernel, tgid: Tid, sig: Signal, info: SigInfo) {
    send_group(k, tgid, sig, info, false);
}

/// A timer counting process CPU time expired: as on Linux the signal is sent to the process, but a
/// running thread is woken to handle it. Linux notices the expiry in the clock interrupt of the
/// thread consuming CPU, so that thread handles it; CPU profilers rely on this to sample a thread
/// that keeps computing in cgo, rather than the first thread.
pub(crate) fn send_cpu_timer(k: &Kernel, tgid: Tid, sig: Signal, info: SigInfo) {
    send_group(k, tgid, sig, info, true);
}

fn send_group(k: &Kernel, tgid: Tid, sig: Signal, info: SigInfo, running: bool) {
    let Some(group) = k.groups.get(&tgid).cloned() else {
        return;
    };
    let threads: Vec<Rc<Task>> = group
        .borrow()
        .threads
        .iter()
        .filter_map(|t| k.tasks.get(t).cloned())
        .collect();
    let Some(leader) = threads.first() else {
        return;
    };
    let blocked = leader.sigmask.get() & sig.bit() != 0;
    let traced = crate::ptrace::traced(leader);
    let target = for_target(&group.borrow(), sig, info, blocked, traced);
    if sig == Signal::KILL {
        if target.is_some() {
            group_exit(k, &group, killed_by(sig));
        }
        return;
    }
    prepare(k, &group, sig);
    let Some(info) = target else {
        return;
    };
    let ignored = group.borrow().sighand.borrow().ignores(sig);
    if ignored && !blocked && !traced {
        return;
    }
    {
        let room = sig.is_realtime() && queue_room(k, &group.borrow());
        group.borrow_mut().pending.add(sig, info, room);
    }
    // Linux's wants_signal: a thread that blocks the signal, or sits in a ptrace stop, does not
    // take it; another one is chosen
    let unmasked =
        |t: &&Rc<Task>| t.sigmask.get() & sig.bit() == 0 && t.trace.borrow().stop.is_none();
    let target = if running {
        // When several threads are running, take turns, roughly sharing by CPU time
        static TURN: AtomicUsize = AtomicUsize::new(0);
        let busy: Vec<_> = threads
            .iter()
            .filter(unmasked)
            .filter(|t| !t.sleeping.load(std::sync::atomic::Ordering::Relaxed))
            .collect();
        let turn = TURN.fetch_add(1, Ordering::Relaxed);
        busy.get(turn % busy.len().max(1)).copied()
    } else {
        None
    };
    match target.or_else(|| threads.iter().find(unmasked)) {
        Some(t) => wake(t),
        // Every thread blocks it: threads waiting in sigtimedwait or signalfd must recheck
        None => request_wake_on(wake::SIGNAL),
    }
}

/// Before a signal is sent to `group` (Linux's `send_signal_locked`, `sig_task_ignored`): when
/// the sender cannot be seen in its pid namespace, si_pid becomes 0. Process 1 of a pid namespace
/// does not receive default-handled signals, except SIGKILL and SIGSTOP sent from an ancestor
/// namespace or generated by the kernel; when not blocked and not traced they are dropped here
/// (returning None), blocked ones are dropped at delivery ([`deliver`]).
fn for_target(
    group: &ThreadGroup,
    sig: Signal,
    mut info: SigInfo,
    blocked: bool,
    traced: bool,
) -> Option<SigInfo> {
    info.retarget_uid(&group.cred);
    let ns = &group.pid_ns;
    if ns.level == 0 {
        return Some(info);
    }
    let mut force = info.code == code::SI_KERNEL;
    if info.sender != 0 && !ns.sees(info.sender) {
        info.hide_sender();
        force = true;
    }
    let ignored = unkillable(group)
        && (!blocked && !traced || sig == Signal::KILL)
        && group.sighand.borrow().get(sig).handler == SigAction::DEFAULT
        && !(force && (sig == Signal::KILL || sig == Signal::STOP));
    (!ignored).then_some(info)
}

/// Process `group` is process 1 of a pid namespace (Linux's `SIGNAL_UNKILLABLE`).
fn unkillable(group: &ThreadGroup) -> bool {
    group.pid_ns.level > 0 && group.pid_ns.reaper.get() == Some(group.tgid) && !group.killable
}

/// Ends the whole thread group (exit_group, a fatal signal, a SIGKILL not from execve): records
/// the exit status and makes every thread exit the next time it enters the kernel.
pub(crate) fn group_exit(k: &Kernel, group: &Rc<RefCell<ThreadGroup>>, status: ExitStatus) {
    let mut g = group.borrow_mut();
    if g.exiting.is_none() {
        g.exiting = Some(status);
    }
    k.cgroups.task_changed(g.cgroup);
    for tid in &g.threads {
        if let Some(t) = k.tasks.get(tid) {
            t.killed.set(true);
            wake(t);
        }
    }
}

fn killed_by(sig: Signal) -> ExitStatus {
    ExitStatus::Signaled {
        signal: sig,
        pc: None,
        fault_addr: None,
        core_dumped: false,
    }
}

/// Stop signals: SIGSTOP, SIGTSTP, SIGTTIN, SIGTTOU.
const STOP_SIGNALS: u64 = (1 << (19 - 1)) | (1 << (20 - 1)) | (1 << (21 - 1)) | (1 << (22 - 1));

/// The part that takes effect as soon as a signal is generated (Linux's `prepare_signal`): a stop
/// signal discards pending SIGCONT; SIGCONT discards pending stop signals and resumes a stopped
/// thread group, whether or not it is blocked or ignored.
fn prepare(k: &Kernel, group: &Rc<RefCell<ThreadGroup>>, sig: Signal) {
    let clear = |mask: u64| {
        let mut g = group.borrow_mut();
        g.pending.discard(mask);
        for t in g.threads.iter().filter_map(|t| k.tasks.get(t)) {
            t.pending.borrow_mut().discard(mask);
        }
    };
    if sig.is_stop() {
        clear(Signal::CONT.bit());
    } else if sig == Signal::CONT {
        clear(STOP_SIGNALS);
        let resumed = {
            let mut g = group.borrow_mut();
            let was = std::mem::take(&mut g.stopped);
            if was {
                g.stop_report = None;
                g.cont_report = true;
            }
            was
        };
        if resumed {
            notify_parent(k, group, code::CLD_CONTINUED, Signal::CONT.number());
            request_wake();
        }
        // Traced threads no longer join the group-stop; those in PTRACE_LISTEN must report again
        // (crate::ptrace)
        for t in group.borrow().threads.iter().filter_map(|t| k.tasks.get(t)) {
            let mut trace = t.trace.borrow_mut();
            trace.group_stop = None;
            if trace.listening {
                drop(trace);
                wake(t);
            }
        }
    }
}

/// Notifies the parent when a child stops or continues: wakes the parent waiting in wait, and
/// sends SIGCHLD unless `SA_NOCLDSTOP` is set.
fn notify_parent(k: &Kernel, group: &Rc<RefCell<ThreadGroup>>, code: i32, status: i32) {
    let (tgid, ppid) = {
        let g = group.borrow();
        (g.tgid, g.ppid)
    };
    request_wake_on(wake::CHILD);
    let Some(parent) = k.groups.get(&ppid) else {
        return;
    };
    let act = parent.borrow().sighand.borrow().get(Signal::CHLD);
    if act.flags & sa::NOCLDSTOP == 0 {
        let pid = k.pid_seen_by(ppid, tgid);
        let info = child_info(&group.borrow().cred, &parent.borrow().cred, |uid| {
            SigInfo::child_event(pid, uid, code, status)
        });
        send_to_group(k, ppid, Signal::CHLD, info);
    }
}

/// The SIGCHLD sent to the parent or tracer (`parent`) when a child (with credentials `child`)
/// stops or continues: si_uid is the child's real user ID as seen in the parent's namespace, and
/// like any other signal it is then converted once more, as sent by the child itself (Linux's
/// `do_notify_parent_cldstop` uses `send_signal_locked`; when the child is in another user
/// namespace, IDs unmappable there become 65534). The SIGCHLD at exit is not converted again
/// (`do_notify_parent` uses `__send_signal_locked`), see [`exit_info`].
pub(crate) fn child_info(child: &Cred, parent: &Cred, f: impl FnOnce(u32) -> SigInfo) -> SigInfo {
    f(parent.uid_out(child.ruid)).sent_by(child)
}

/// The SIGCHLD at a child's exit: si_uid is the child's real user ID as seen in the parent's
/// namespace.
pub(crate) fn exit_info(child: &Cred, parent: &Cred, pid: Tid, status: ExitStatus) -> SigInfo {
    SigInfo::child(pid, parent.uid_out(child.ruid), status)
}

/// When sigqueue sends a real-time signal and the thread group's queue is full, it must return
/// EAGAIN instead of dropping the siginfo.
pub(crate) fn can_queue(k: &Kernel, tgid: Tid, sig: Signal) -> bool {
    !sig.is_realtime()
        || k.groups
            .get(&tgid)
            .is_none_or(|g| queue_room(k, &g.borrow()))
}

/// Whether a real-time signal can still be queued: a thread group queues at most
/// `RLIMIT_SIGPENDING` (Linux counts per user).
fn queue_room(k: &Kernel, group: &ThreadGroup) -> bool {
    (queued(k, group) as u64) < group.rlimits[RLIMIT_SIGPENDING as usize].0
}

/// The number of real-time signals queued in the thread group (SigQ in `/proc/<pid>/status`).
pub(crate) fn queued(k: &Kernel, group: &ThreadGroup) -> usize {
    let threads = group.threads.iter().filter_map(|t| k.tasks.get(t));
    group.pending.queued() + threads.map(|t| t.pending.borrow().queued()).sum::<usize>()
}

/// Makes a thread enter the kernel as soon as possible: kicks guest code it is running, and wakes
/// it if it is waiting.
pub(crate) fn wake(task: &Task) {
    // SAFETY: a thread is removed from kernel.tasks (with the BKL held) before its Cpu is
    // destroyed, and the BKL is held here too
    unsafe { task.sync.kicker.kick() };
    crate::kernel::signal_later(&task.event);
}

/// A synchronous exception: when the signal is blocked or ignored, restores the default
/// disposition and unblocks it (Linux's `force_sig_info`), then makes it pending on the current
/// thread.
pub(crate) fn force(cx: &mut Cx<'_>, sig: Signal, info: SigInfo) {
    let blocked = cx.task.sigmask.get() & sig.bit() != 0;
    let default = {
        let group = cx.t.group.borrow();
        let mut sh = group.sighand.borrow_mut();
        let mut act = sh.get(sig);
        if blocked || act.handler == SigAction::IGNORE {
            act.handler = SigAction::DEFAULT;
            sh.set(sig, act);
        }
        act.handler == SigAction::DEFAULT
    };
    // Under the default disposition it also kills process 1 of a pid namespace, except when
    // traced (the tracer sees it first)
    if default && !crate::ptrace::traced(cx.task) {
        cx.t.group.borrow_mut().killable = true;
    }
    if blocked {
        cx.task.sigmask.set(cx.task.sigmask.get() & !sig.bit());
    }
    cx.task.pending.borrow_mut().add(sig, info, false);
}

/// seccomp kills the process (Linux's `force_sig_info_to_task(..., HANDLER_EXIT)`): whatever the
/// previous disposition, restores the default and unblocks the signal, so that it can no longer be
/// changed and tracers cannot intercept it (`SA_IMMUTABLE`), then makes it pending on the current
/// thread. The default action ends the process (SIGSYS writes a core).
pub(crate) fn force_fatal(cx: &mut Cx<'_>, sig: Signal, info: SigInfo) {
    {
        let group = cx.t.group.borrow();
        let mut sh = group.sighand.borrow_mut();
        let act = SigAction {
            handler: SigAction::DEFAULT,
            immutable: true,
            ..sh.get(sig)
        };
        sh.set(sig, act);
    }
    cx.t.group.borrow_mut().killable = true;
    cx.task.sigmask.set(cx.task.sigmask.get() & !sig.bit());
    cx.task.pending.borrow_mut().add(sig, info, false);
}

