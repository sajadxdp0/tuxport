// lockstep's native execution trampoline.
//
// The whole code is copied into a JIT page, with the tested instructions (at most 4) written at
// lockstep_tramp_slot, so only position-independent instructions that reference no external
// symbols can be used here. The tested instructions must not read or write SP, and all register
// saving and restoring goes through the stack.
//
//   void tramp(struct lockstep_state *st);
//
//   st: x[31] @0, nzcv @248, v[32] @256, fpcr @768, fpsr @776

    .text
    .p2align 2
    .globl  lockstep_tramp_start
    .globl  lockstep_tramp_slot
    .globl  lockstep_tramp_end

lockstep_tramp_start:
    stp     x29, x30, [sp, #-16]!
    stp     x27, x28, [sp, #-16]!
    stp     x25, x26, [sp, #-16]!
    stp     x23, x24, [sp, #-16]!
    stp     x21, x22, [sp, #-16]!
    stp     x19, x20, [sp, #-16]!
    stp     d8, d9, [sp, #-16]!
    stp     d10, d11, [sp, #-16]!
    stp     d12, d13, [sp, #-16]!
    stp     d14, d15, [sp, #-16]!
    mrs     x1, fpcr
    stp     x0, x1, [sp, #-16]!         // st and the host FPCR

    ldr     x1, [x0, #768]
    msr     fpcr, x1
    ldr     x1, [x0, #776]
    msr     fpsr, x1
    add     x1, x0, #256
    ldp     q0, q1, [x1, #0]
    ldp     q2, q3, [x1, #32]
    ldp     q4, q5, [x1, #64]
    ldp     q6, q7, [x1, #96]
    ldp     q8, q9, [x1, #128]
    ldp     q10, q11, [x1, #160]
    ldp     q12, q13, [x1, #192]
    ldp     q14, q15, [x1, #224]
    ldp     q16, q17, [x1, #256]
    ldp     q18, q19, [x1, #288]
    ldp     q20, q21, [x1, #320]
    ldp     q22, q23, [x1, #352]
    ldp     q24, q25, [x1, #384]
    ldp     q26, q27, [x1, #416]
    ldp     q28, q29, [x1, #448]
    ldp     q30, q31, [x1, #480]
    ldr     x1, [x0, #248]
    msr     nzcv, x1
    ldp     x2, x3, [x0, #16]
    ldp     x4, x5, [x0, #32]
    ldp     x6, x7, [x0, #48]
    ldp     x8, x9, [x0, #64]
    ldp     x10, x11, [x0, #80]
    ldp     x12, x13, [x0, #96]
    ldp     x14, x15, [x0, #112]
    ldp     x16, x17, [x0, #128]
    ldp     x18, x19, [x0, #144]
    ldp     x20, x21, [x0, #160]
    ldp     x22, x23, [x0, #176]
    ldp     x24, x25, [x0, #192]
    ldp     x26, x27, [x0, #208]
    ldp     x28, x29, [x0, #224]
    ldr     x30, [x0, #240]
    ldp     x0, x1, [x0]

lockstep_tramp_slot:
    nop                                 // tested instructions, at most 4
    nop
    nop
    nop

    sub     sp, sp, #256
    stp     x0, x1, [sp, #0]
    stp     x2, x3, [sp, #16]
    stp     x4, x5, [sp, #32]
    stp     x6, x7, [sp, #48]
    stp     x8, x9, [sp, #64]
    stp     x10, x11, [sp, #80]
    stp     x12, x13, [sp, #96]
    stp     x14, x15, [sp, #112]
    stp     x16, x17, [sp, #128]
    stp     x18, x19, [sp, #144]
    stp     x20, x21, [sp, #160]
    stp     x22, x23, [sp, #176]
    stp     x24, x25, [sp, #192]
    stp     x26, x27, [sp, #208]
    stp     x28, x29, [sp, #224]
    mrs     x0, nzcv
    stp     x30, x0, [sp, #240]

    ldr     x0, [sp, #256]              // st
    mov     x1, #0
1:  ldr     x2, [sp, x1]
    str     x2, [x0, x1]
    add     x1, x1, #8
    cmp     x1, #256
    b.ne    1b
    add     x1, x0, #256                // the V registers have not been touched yet
    stp     q0, q1, [x1, #0]
    stp     q2, q3, [x1, #32]
    stp     q4, q5, [x1, #64]
    stp     q6, q7, [x1, #96]
    stp     q8, q9, [x1, #128]
    stp     q10, q11, [x1, #160]
    stp     q12, q13, [x1, #192]
    stp     q14, q15, [x1, #224]
    stp     q16, q17, [x1, #256]
    stp     q18, q19, [x1, #288]
    stp     q20, q21, [x1, #320]
    stp     q22, q23, [x1, #352]
    stp     q24, q25, [x1, #384]
    stp     q26, q27, [x1, #416]
    stp     q28, q29, [x1, #448]
    stp     q30, q31, [x1, #480]
    mrs     x2, fpsr
    str     x2, [x0, #776]
    mrs     x2, fpcr
    str     x2, [x0, #768]

    add     sp, sp, #256
    ldp     x0, x1, [sp], #16
    msr     fpcr, x1                    // restore the host FPCR
    ldp     d14, d15, [sp], #16
    ldp     d12, d13, [sp], #16
    ldp     d10, d11, [sp], #16
    ldp     d8, d9, [sp], #16
    ldp     x19, x20, [sp], #16
    ldp     x21, x22, [sp], #16
    ldp     x23, x24, [sp], #16
    ldp     x25, x26, [sp], #16
    ldp     x27, x28, [sp], #16
    ldp     x29, x30, [sp], #16
    ret
lockstep_tramp_end:

    .section .note.GNU-stack, "", %progbits
